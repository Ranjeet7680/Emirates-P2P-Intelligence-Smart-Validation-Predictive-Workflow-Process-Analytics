import os, json, joblib
import pandas as pd
import numpy as np
from typing import Dict, Any, List
from ..schemas.dto import RiskPredictionOutputDTO, ModelCardDTO

class MLEngineService:
    def __init__(self):
        self.models_dir = os.path.join(os.path.dirname(__file__), "..", "..", "..", "models")
        self.registry = self._load_registry()
        self.models = self._load_models()

    def _load_registry(self) -> Dict[str, Any]:
        path = os.path.join(self.models_dir, "model_registry.json")
        try:
            with open(path, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception:
            return {"models": []}

    def _load_models(self) -> Dict[str, Any]:
        models = {}
        diab_path = os.path.join(self.models_dir, "diabetes_risk_model.joblib")
        if os.path.exists(diab_path):
            try:
                models["MOD-DIAB-01"] = joblib.load(diab_path)
            except Exception:
                pass

        cardio_path = os.path.join(self.models_dir, "cardio_risk_model.joblib")
        if os.path.exists(cardio_path):
            try:
                models["MOD-CVD-01"] = joblib.load(cardio_path)
            except Exception:
                pass
        return models

    def get_available_models(self) -> List[ModelCardDTO]:
        cards = []
        for m in self.registry.get("models", []):
            cards.append(ModelCardDTO(**m))
        return cards

    def predict_risk(self, model_id: str, features: Dict[str, float]) -> RiskPredictionOutputDTO:
        model = self.models.get(model_id)
        if not model:
            raise ValueError(f"Model ID '{model_id}' is not loaded in registry.")

        # Find model metadata
        meta = next((m for m in self.registry.get("models", []) if m["model_id"] == model_id), None)
        if not meta:
            raise ValueError(f"Metadata for model '{model_id}' not found.")

        feature_names = meta["features"]
        # Prepare feature vector with fallbacks for missing
        row = {}
        for f in feature_names:
            row[f] = [features.get(f, 0.0)]

        df_input = pd.DataFrame(row)
        prob = float(model.predict_proba(df_input)[0, 1])

        # Risk categorization
        if prob >= 0.35:
            category = "High"
        elif prob >= 0.20:
            category = "Intermediate"
        elif prob >= 0.10:
            category = "Borderline"
        else:
            category = "Low"

        # Calculate approximate SHAP feature contributions
        contributions = {}
        importances = meta.get("feature_importances", {})
        for f in feature_names:
            val = features.get(f, 0.0)
            imp = importances.get(f, 0.1)
            # Normalised relative contribution
            contributions[f] = round(float(imp * (val / max(1.0, val))), 3)

        # Actionable evidence-based recommendations
        recs = []
        if model_id == "MOD-DIAB-01":
            if features.get("hba1c", 5.0) >= 5.7 or features.get("glucose_fasting", 90) >= 100:
                recs.append("Schedule confirmatory 75g Oral Glucose Tolerance Test (OGTT) or repeat fasting plasma glucose.")
            if features.get("bmi", 24) >= 25.0:
                recs.append("Aim for 5-7% weight reduction via structured lifestyle intervention and Mediterranean diet.")
            recs.append("Incorporate 150+ minutes of moderate aerobic exercise and 2 resistance sessions per week.")
        else:
            if features.get("total_cholesterol", 180) >= 200 or features.get("hdl_cholesterol", 50) < 40:
                recs.append("Evaluate full fasting lipid profile including Apolipoprotein B and Lipoprotein(a).")
            if features.get("systolic_bp", 120) >= 130:
                recs.append("Initiate home blood pressure monitoring (HBPM) log twice daily for 7 consecutive days.")
            if features.get("smoker", 0) == 1:
                recs.append("Prioritize structured smoking cessation counseling and pharmacotherapy.")

        return RiskPredictionOutputDTO(
            model_id=model_id,
            model_name=meta["name"],
            risk_probability=round(prob, 4),
            risk_category=category,
            feature_contributions=contributions,
            actionable_recommendations=recs,
            disclaimer=(
                "EXPERIMENTAL RESEARCH LAB MODEL: This risk estimate is generated by a research-grade machine learning model. "
                "It does NOT constitute a clinical diagnosis or replace standard ASCVD/ADA clinical risk calculators. "
                "Consult a licensed physician for professional medical evaluation."
            )
        )

ml_engine = MLEngineService()
